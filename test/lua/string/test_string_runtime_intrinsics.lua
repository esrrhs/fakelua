function test_runtime_string_intrinsics()
    local text = runtime_string_value("AbC")
    assert(string.lower(text) == "abc")
    assert(string.upper(text) == "ABC")
    assert(string.reverse(text) == "CbA")
    assert(string.rep(text, 2) == "AbCAbC")
    assert(string.rep(text, -1) == "")
    assert(string.byte(text, 2) == 98)
    assert(string.byte(text, 4) == nil)
    local begin, finish = string.find(text, runtime_string_value("b"), 1, true)
    assert(begin == 2 and finish == 2)
    assert(string.find(text, runtime_string_value("missing"), 1, true) == nil)
    assert(string.lower(runtime_string_value(123)) == "123")
    assert(string.upper(runtime_string_value(123)) == "123")
    assert(string.reverse(runtime_string_value(123)) == "321")
    assert(string.rep(runtime_string_value(12), 2) == "1212")
    assert(string.byte(runtime_string_value(65), 1) == 54)
    local first, last = string.find(runtime_string_value(12345), runtime_string_value(23), 1, true)
    assert(first == 2 and last == 3)
    return 1
end
