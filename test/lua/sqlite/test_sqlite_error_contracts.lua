function test_sqlite_error_contracts(missing_path)
    assert(not pcall(function() return sqlite.open(missing_path) end))
    local db = sqlite.open(":memory:")
    local ok, err = pcall(function()
        assert(not pcall(function() return db:exec("not valid SQL") end))
        assert(not pcall(function() return db:prepare("not valid SQL") end))
        assert(not pcall(function() return db:exec("SELECT abs(-9223372036854775808)") end))
        db:exec("CREATE TABLE entries(value INTEGER UNIQUE)")
        local stmt = db:prepare("INSERT INTO entries VALUES (?)")
        assert(not pcall(function() return stmt:bind({}) end))
        assert(not pcall(function() return stmt:bind(1, 2) end))
        stmt:bind(true)
        assert(stmt:step() == nil)
        stmt:reset()
        stmt:bind(false)
        assert(stmt:step() == nil)
        stmt:reset()
        stmt:bind(true)
        assert(not pcall(function() return stmt:step() end))
        assert(not pcall(function() return stmt:reset() end))
        stmt:close()
        assert(not pcall(function() return db:exec("INSERT INTO entries VALUES (1)") end))
        stmt = db:prepare("INSERT INTO entries VALUES (1)")
        assert(not pcall(function() return stmt:step() end))
        assert(not pcall(function() return stmt:close() end))
        stmt:close()
        local rows = db:exec("SELECT value FROM entries ORDER BY value")
        assert(#rows == 2 and rows[1].value == 0 and rows[2].value == 1)
    end)
    db:close()
    assert(ok, err)
    return 1
end
