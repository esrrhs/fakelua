function test_ordered_scalar_keys()
    local map = container.map()
    map:set(nil, "nil")
    map:set(false, "false")
    map:set(true, "true")
    map:set(1.0, "one")
    map:set(1.5, "fraction")
    map:set(0/0, "nan")
    assert(map:size() == 6)
    assert(map:get(nil) == "nil")
    assert(map:get(1) == "one")
    assert(map:get(1.5) == "fraction")
    assert(map:get(0/0) == "nan")
    local keys = map:keys()
    assert(keys[1] == nil and keys[2] == false and keys[3] == true)
    assert(keys[4] == 1 and keys[5] == 1.5 and keys[6] ~= keys[6])
    assert(not pcall(function() map:set({}, 1) end))
    assert(not pcall(function() map:set(function() return 1 end, 1) end))
    assert(map:erase(nil) and not map:has(nil))
    local set = container.set()
    assert(set:insert(nil) and not set:insert(nil))
    assert(set:insert(1.0) and not set:insert(1))
    assert(set:insert(1.5) and set:insert(0/0))
    assert(set:has(0/0) and set:has(1.5))
    assert(not pcall(function() set:insert({}) end))
    map:clear()
    set:clear()
    assert(map:empty() and set:empty())
    return 1
end
