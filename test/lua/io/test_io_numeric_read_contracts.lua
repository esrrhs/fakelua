function test_numeric_read_contracts()
    local file = io.tmpfile()
    assert(file ~= nil)
    local original = io.input()
    local ok, err = pcall(function()
        file:write("abc\n123\nZ")
        file:seek("set", 0)
        assert(file:read(0) == "")
        assert(file:read(3) == "abc")
        assert(file:read() == "")
        assert(not pcall(function() return file:read(-1) end))
        assert(not pcall(function() return file:read(67108865) end))
        assert(not pcall(function() return file:read("67108865") end))
        assert(not pcall(function() return file:read("999999999999999999999999999999") end))
        assert(not pcall(function() return file:read("*invalid") end))
        assert(not pcall(function() return file:read(true) end))
        io.input(file)
        assert(io.read() == "123")
        local first, last = io.read(1, 1)
        assert(first == "Z" and last == nil)
        assert(io.read(0) == nil)
        file:seek("set", 0)
        local iterator = io.lines()
        assert(iterator() == "abc" and iterator() == "123" and iterator() == "Z")
        assert(iterator() == nil)
        local pipe, message = io.popen("")
        assert(pipe == nil and message == "missing command")
    end)
    io.input(original)
    file:close()
    assert(ok, err)
    return 1
end
